import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { NPC_DATABASE } from '../services/npcLogic';
import { processGameWeek } from '../services/gameLoop';
import { readCinemaAuditCheckpoint, cinemaAuditClock, cinemaAuditRandom } from './fixtures/cinemaAuditCheckpoint';
const saved = readCinemaAuditCheckpoint<any>('cinema-verification.local/owned-studio-20261029/earned-owned-prefix/career-0.json.gz');
NPC_DATABASE.length = 0; NPC_DATABASE.push(...saved.npcDatabase); delete saved.npcDatabase;
const player = saved.player; delete saved.player;
const random = cinemaAuditRandom('normal-cinema-cohort:0', saved.randomCalls || 0), clock = cinemaAuditClock(saved.clockNext);
Math.random = random.next; Date.now = clock.now;
const hash = (v: unknown) => createHash('sha256').update(JSON.stringify(v)).digest('hex');
const prior = hash(player), at = performance.now(), result = await processGameWeek(player), elapsedMs = performance.now() - at;
assert.equal(hash(player), prior, 'The complete prior player must remain unchanged');
const batches = (globalThis as any).__viewingReadinessBatches as Array<{ calls: number; titles: Set<string> }>;
assert.ok(batches.some(batch => batch.titles.size > 0), 'The real career must exercise cinema-backed streaming titles');
const output = { elapsedMs, completePlayerJsonSha256: hash(result.player), randomCalls: random.calls(), clockNext: clock.next(), batches: batches.map(b => ({ calls: b.calls, uniqueTitles: b.titles.size })) };
if (process.env.READINESS_COST_OUTPUT) writeFileSync(process.env.READINESS_COST_OUTPUT, JSON.stringify(output, null, 2));
for (const batch of batches) assert.ok(batch.calls <= batch.titles.size, `A fixed viewing projection must resolve each title at most once; calls=${batch.calls}, unique=${batch.titles.size}`);
console.log(JSON.stringify(output));
