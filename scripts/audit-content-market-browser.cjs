// Run against the local Vite server. The fixture is isolated from all game save slots.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:3000/scripts/fixtures/content-market-cm1.html');
    await page.waitForLoadState('networkidle');
    await page.getByRole('button', { name: 'Explore on my own', exact: true }).click();
    await page.getByRole('button', { name: 'CONTENT MARKET', exact: true }).click();
    await page.getByRole('heading', { name: 'Find your next title.' }).waitFor();
    const initialBrand = await page.locator('.cm-market').evaluate(el => getComputedStyle(el).getPropertyValue('--epx-brand'));
    await page.screenshot({ path: '/tmp/cm1-market-mobile.png' });
    await page.getByRole('textbox', { name: 'Search content' }).fill('Harbour 1');
    await page.waitForFunction(() => JSON.parse(sessionStorage.getItem('cm1-isolated-player') || '{}').ownedStreamingPlatform?.contentMarketDraft?.search === 'Harbour 1', null, { timeout: 2500 });
    await page.locator('.cm-row').filter({ hasText: 'The Harbour 1' }).click();
    await page.getByRole('button', { name: 'Studio Finance', exact: true }).click();
    await page.getByRole('button', { name: /TRANSFER \$/i }).click();
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    await page.getByRole('heading', { name: 'The Harbour 1', exact: true }).waitFor();
    assert.ok((await page.locator('.cm-funds').innerText()).includes('$730M'), 'Finance return preserves listing and updates treasury');
    await page.getByRole('button', { name: /Accept listed terms/ }).click();
    assert.ok((await page.locator('.cm-feedback').innerText()).includes('added to your catalogue'));
    await page.getByRole('button', { name: 'Back to Content Desk', exact: true }).click();
    assert.ok((await page.locator('body').innerText()).includes('READY TO SCHEDULE'));
    await page.getByRole('button', { name: '+ ADD CONTENT', exact: true }).click();
    await page.getByRole('textbox', { name: 'Search content' }).fill('');
    await page.getByLabel('Content source').getByRole('button', { name: 'My studio', exact: true }).click();
    await page.locator('.cm-row').filter({ hasText: 'The Last Light' }).click();
    await page.getByRole('button', { name: /Add 1 studio title/ }).click();
    await page.getByRole('button', { name: 'Back to Content Desk', exact: true }).click();
    assert.ok((await page.locator('body').innerText()).includes('Studio import'));
    await page.screenshot({ path: '/tmp/cm1-library-mobile.png' });
    await page.getByRole('button', { name: /The Last Light/ }).click();
    assert.ok((await page.locator('body').innerText()).includes('STUDIO IMPORT FILM'), 'Title detail must not label a studio import as licensed');
    await page.getByRole('button', { name: 'Close', exact: true }).click();
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    await page.getByRole('button', { name: /define the launch/i }).click();
    await page.getByRole('button', { name: 'Assemble opening night', exact: true }).click();
    await page.getByRole('button', { name: 'Review opening catalogue', exact: true }).click();
    await page.getByRole('dialog', { name: 'Opening Catalogue', exact: true }).waitFor();
    await page.getByRole('dialog', { name: 'Opening Catalogue', exact: true }).getByRole('button', { name: '+ ADD CONTENT', exact: true }).click();
    await page.getByRole('button', { name: 'Return to launch plan', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Assemble opening night', exact: true }).getAttribute('aria-current'), 'step');
    await page.getByRole('button', { name: 'Open Content Desk', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: '+ ADD CONTENT', exact: true }).count(), 1);
    await page.getByRole('button', { name: 'Back', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Assemble opening night', exact: true }).getAttribute('aria-current'), 'step', 'Library opened from launch returns to Catalogue');
    await page.getByRole('button', { name: 'Review opening catalogue', exact: true }).click();
    await page.getByRole('dialog', { name: 'Opening Catalogue', exact: true }).getByRole('button', { name: '+ ADD CONTENT', exact: true }).click();
    await page.getByRole('button', { name: 'Collections', exact: true }).click();
    await page.locator('.cm-market .cm-row').first().click();
    await page.getByRole('heading', { name: 'Title breakdown' }).waitFor();
    await page.setViewportSize({ width: 320, height: 740 });
    assert.equal(await page.locator('.cm-market').evaluate(el => el.scrollWidth <= el.clientWidth), true, 'Market fits a 320px screen without page overflow');
    await page.screenshot({ path: '/tmp/cm1-collection-320.png' });
    await page.getByRole('button', { name: /Acquire collection/ }).click();
    assert.ok((await page.locator('.cm-feedback').innerText()).includes('added to your catalogue'));
    await page.getByRole('button', { name: 'Return to launch plan', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Assemble opening night', exact: true }).getAttribute('aria-current'), 'step');
    await page.reload();
    await page.getByRole('button', { name: 'CONTENT MARKET', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Collections', exact: true }).getAttribute('aria-pressed'), 'true', 'Saved filter survives reload');
    const first = await browser.newPage({ viewport: { width: 390, height: 844 } });
    first.on('pageerror', error => errors.push(error.message));
    await first.goto('http://127.0.0.1:3000/scripts/fixtures/content-market-cm1.html?noStudio=1&gold=1');
    await first.getByRole('button', { name: 'Explore on my own', exact: true }).click();
    await first.getByRole('button', { name: 'CONTENT MARKET', exact: true }).click();
    assert.notEqual(await first.locator('.cm-market').evaluate(el => getComputedStyle(el).getPropertyValue('--epx-brand')), initialBrand, 'The market inherits each platform brand instead of using fixed purple');
    await first.locator('.cm-market .cm-row').first().click();
    await first.getByRole('button', { name: /Accept listed terms/ }).click();
    assert.ok((await first.locator('.cm-feedback').innerText()).includes('added to your catalogue'), 'No production house is needed to buy released content');
    await first.getByRole('button', { name: /Commission an Original/ }).click();
    assert.ok((await first.locator('body').innerText()).includes('COMMISSION ORIGINAL'));
    const privatePage = await browser.newPage({ viewport: { width: 390, height: 844 } });
    privatePage.on('pageerror', error => errors.push(error.message));
    await privatePage.goto('http://127.0.0.1:3000/scripts/fixtures/content-market-cm1.html?private=1');
    await privatePage.getByRole('button', { name: 'Explore on my own', exact: true }).click();
    await privatePage.getByRole('button', { name: 'CONTENT MARKET', exact: true }).click();
    await privatePage.locator('.cm-market .cm-row').first().click();
    await privatePage.getByRole('button', { name: /Make private offer/ }).click();
    await privatePage.getByRole('region', { name: 'Private offer terms' }).waitFor();
    await privatePage.getByRole('button', { name: 'Deal protections' }).click();
    assert.equal(await privatePage.getByRole('region', { name: 'Private offer terms' }).getByText('Renewal option', { exact: true }).count(), 1, 'Advanced clauses stay available behind one disclosure');
    assert.equal(await privatePage.getByRole('combobox', { name: 'Change of control' }).count(), 1, 'The complete advanced term sheet includes change-of-control protection');
    await privatePage.getByRole('button', { name: 'Send private offer', exact: true }).click();
    await privatePage.getByText(/Awaiting reply · [23] weeks/).waitFor();
    assert.ok((await privatePage.locator('.cm-feedback').innerText()).includes('Private offer sent'));
    await privatePage.getByRole('button', { name: /Your offers/ }).click();
    await privatePage.getByRole('heading', { name: 'Your offers.' }).waitFor();
    await privatePage.setViewportSize({ width: 320, height: 740 });
    assert.equal(await privatePage.locator('.cm-market').evaluate(el => el.scrollWidth <= el.clientWidth), true, 'Private offers fit 320px without horizontal overflow');
    await privatePage.screenshot({ path: '/tmp/cm2-private-offer-mobile.png' });
    const auctionPage = await browser.newPage({ viewport: { width: 390, height: 844 } });
    auctionPage.on('pageerror', error => errors.push(error.message));
    await auctionPage.goto('http://127.0.0.1:3000/scripts/fixtures/content-market-cm1.html?auction=1');
    await auctionPage.getByRole('button', { name: 'Explore on my own', exact: true }).click();
    await auctionPage.getByRole('button', { name: 'CONTENT MARKET', exact: true }).click();
    await auctionPage.getByRole('button', { name: /Live auctions/ }).click();
    await auctionPage.locator('.cm-auction-row').first().click();
    await auctionPage.getByRole('button', { name: 'Enter live auction', exact: true }).click();
    await auctionPage.getByRole('dialog', { name: 'Live rights auction' }).waitFor();
    await auctionPage.getByRole('region', { name: 'Auction offer console' }).waitFor();
    await auctionPage.getByRole('button', { name: /Place bid/ }).click();
    await auctionPage.getByText(/Current commitment/i).waitFor();
    await auctionPage.setViewportSize({ width: 320, height: 740 });
    assert.equal(await auctionPage.locator('.cm-auction-room').evaluate(el => el.scrollWidth <= el.clientWidth), true,
      'The live buyer auction fits a 320px mobile screen without horizontal overflow');
    await auctionPage.screenshot({ path: '/tmp/cm3-live-auction-mobile.png' });
    const messagePage = await browser.newPage({ viewport: { width: 390, height: 844 } });
    messagePage.on('pageerror', error => errors.push(error.message));
    await messagePage.goto('http://127.0.0.1:3000/scripts/fixtures/content-market-cm1.html?message=1');
    await messagePage.getByText(/accepts your offer/i).first().click();
    await messagePage.getByRole('button', { name: 'Open Your Offer', exact: true }).click();
    await messagePage.getByRole('heading', { name: 'The Harbour 1', exact: true }).waitFor();
    assert.ok((await messagePage.locator('.cm-offer-status').innerText()).includes('Accepted'), 'SMS opens the exact accepted Content Market offer');
    await page.screenshot({ path: '/tmp/cm1-hq-mobile.png' });
    assert.equal(await page.locator('vite-error-overlay').count(), 0);
    assert.deepEqual(errors, []);
    console.log('CM1/CM2/CM3 mobile browser passed: direct purchases, finance return, imports, collections, private offers, live buyer auctions, dynamic branding and 320px layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
