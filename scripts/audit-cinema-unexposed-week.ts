import assert from 'node:assert/strict';
import {mixedCinemaFixture} from './audit-box-office-integration';
import * as weekService from '../services/boxOffice/boxOfficeWeek';
import {commitCinemaWeek} from '../services/boxOffice/boxOfficeLiveSettlement';
import {simulateCinemaWeek} from '../services/boxOffice/boxOfficeMarket';
import {clonePlayerForWeekProcessing} from '../services/gameLoopClone';
const close=(weekService as any).processUnexposedOwnedCinemaMarketWeek;
const unexposedInput=(weekService as any).buildUnexposedOwnedCinemaWeekInput;
assert.equal(typeof close,'function','Normal weekly processing needs a player-only synchronous close');
const fixture=mixedCinemaFixture(),before=JSON.stringify(fixture.player);
const normal=weekService.processCinemaMarketWeek(clonePlayerForWeekProcessing(fixture.player),fixture.week,undefined,{reuseDetachedWeekCandidate:true});
const phases:string[]=[],actual=close(clonePlayerForWeekProcessing(fixture.player),fixture.week,{onPhase:(name:string)=>phases.push(name)});
assert.deepEqual(actual,normal.player,'The entire mixed player/NPC/offered-role settlement must match the exposed path');
assert.equal(Object.hasOwn(actual,'result'),false,'The faster owner must not expose an unguarded proposal');
assert.equal(JSON.stringify(fixture.player),before,'The durable source remains untouched');
assert.deepEqual(phases,['cinema_prepare_ms','cinema_input_ms','cinema_simulate_ms','cinema_commit_ms']);
const replay=commitCinemaWeek(actual,normal.result);
assert.equal(replay.applied,false);assert.equal(replay.player,actual,'A full public proposal replays the same receipt without another payment');
const rogueSource=clonePlayerForWeekProcessing(fixture.player),rogueBefore=JSON.stringify(rogueSource);
const rogue=simulateCinemaWeek(unexposedInput(rogueSource,fixture.week));
assert.throws(()=>commitCinemaWeek(rogueSource,rogue),/Cinema source or ownership changed/,'An internal input cannot forge a public source-guarded settlement');
assert.equal(JSON.stringify(rogueSource),rogueBefore);
const broken=mixedCinemaFixture();broken.player.activeReleases.find(r=>r.id==='owned')!.projectDetails.studioId='missing-owner' as never;
const durable=JSON.stringify(broken.player);
assert.throws(()=>close(clonePlayerForWeekProcessing(broken.player),broken.week),/Missing canonical cinema producer/);
assert.equal(JSON.stringify(broken.player),durable,'A late failed close cannot mutate the durable prior player');
console.log(JSON.stringify({passed:11,mixedSettlementExact:true,noResultExposure:true,publicSourceGuardRetained:true,replayPaysNothing:true,failedCandidateDiscardable:true}));
